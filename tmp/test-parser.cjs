function extractInvoices(text) {
  if (!text) return [];
  const cleanText = String(text);

  // Trigger words: рахунок, рах., рах, Счет, сч., №, дог., договір
  // Look for text immediately following these trigger combinations:
  const triggerRegex = /(?:(?:рахун(?:ок|ка|ку|ком|ки|ків)?|рах(?:\.|\b)|счет[а-я]*|сч(?:\.|\b)|догов(?:ір|ору|ором|ори|орів|ор[а-я]*)?|дог(?:\.|\b))\s*(?:[-_–—]\s*фактур[а-я]*)?\s*(?:на\s+оплату\s*)?(?:(?:№|no\.?|n\.?|#)\s*[:.]?\s*)?|(?:№|no\.?|n\.?|#)\s*[:.]?\s*)([A-Za-zА-Яа-яІіЇїЄєҐґ0-9\-_/,.\s+&;іта]+?)(?=(?:\s+(?:від|от)\s+\d{1,2}[./-]\d{1,2}|\s+(?:в\s+т\.?ч\.?|у\s+т\.?ч\.?|т\.?ч\.?|без\s+пдв|пдв|\d+%|сума|грн|за\s+[а-яіїєґ]+)|;|\n|$))/gi;

  const STOP_WORDS = new Set([
    "фарбу", "фарба", "фарби", "краску", "краска",
    "матер", "матеріал", "матеріали", "материалы", "будматеріали", "буд",
    "товар", "товари", "товары",
    "послуги", "послуга", "услуги", "услуга",
    "оплата", "оплачено", "оплатити", "сплата", "розрахунок", "перерахунок",
    "згідно", "зг", "по", "за", "для", "від", "до", "без", "з", "та", "і",
    "аванс", "доплата", "остаточний", "транш",
    "комплектуючі", "фурнітура", "метал", "сталь", "деталі", "вироби", "продукція",
    "рахунок", "рахунку", "рахунка", "рахунком", "рахунки", "рахунків", "рах", "рах.",
    "счет", "счета", "счету", "счетом", "сч", "сч.",
    "договір", "договору", "договором", "договори", "договорів", "договор", "дог", "дог.",
    "інвойс", "інвойсу", "invoice", "пдв", "грн", "грн.", "uah", "коп", "коп.", "т.ч.", "т.ч", "в т.ч.", "у т.ч."
  ]);

  const candidates = [];
  let match;
  while ((match = triggerRegex.exec(cleanText)) !== null) {
    const segment = match[1];
    if (!segment) continue;

    // Split segment into candidate tokens
    const rawTokens = segment.split(/[,;\s+&|]+|\s+(?:та|і|також|а\s+також)\s+/i);
    for (let raw of rawTokens) {
      if (!raw) continue;
      // Strip leading and trailing punctuation (except inside codes like RF26_1611 or Ц-000117212 or 142/26)
      let token = raw.trim().replace(/^[№#№:.,;("'\-]+/, "").replace(/[.,;)"'\-]+$/, "").trim();
      if (!token) continue;

      // 1. Must contain at least one digit
      if (!/\d/.test(token)) continue;

      // 2. Reject decimal amounts like 1369.18 or 24195.30 or 1500,00
      if (/^\d+[,.]\d+$/.test(token)) continue;

      // 3. Reject percentages like 20%
      if (token.includes("%")) continue;

      // 4. Reject dates like 12.08.2026 or 12.08.26 or 2026-08-12
      if (/^\d{1,2}[./-]\d{1,2}[./-]\d{2,4}$/.test(token) || /^\d{4}[./-]\d{2}[./-]\d{2}$/.test(token)) continue;

      // 5. Reject stop words or currency
      const lower = token.toLowerCase();
      if (STOP_WORDS.has(lower)) continue;

      // 6. Valid invoice code check:
      // Pattern: numeric or alphanumeric code, optionally with prefixes, dashes, slashes, underscores
      if (/^[A-Za-zА-Яа-яІіЇїЄєҐґ0-9][A-Za-zА-Яа-яІіЇїЄєҐґ0-9\-_/]*\d[A-Za-zА-Яа-яІіЇїЄєҐґ0-9\-_/]*$/i.test(token)) {
        if (!candidates.includes(token)) {
          candidates.push(token);
        }
      }
    }
  }

  return candidates;
}

